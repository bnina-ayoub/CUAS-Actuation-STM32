void subscription_callback(const void * msgin)
{
  const sensor_msgs__msg__JointState * msg =
      (const sensor_msgs__msg__JointState *)msgin;

  HAL_GPIO_TogglePin(GPIOA, GPIO_PIN_5);

  if (msg->velocity.size > 0) {
    joint_target.pan_velocity = (float)msg->velocity.data[0];
  }

  if (msg->velocity.size > 1) {
    joint_target.tilt_velocity = (float)msg->velocity.data[1];
  }

  osThreadFlagsSet(UART_TaskHandle, 0x0001);

}

int usleep(useconds_t usec)
{
    // Convert microseconds to milliseconds
    uint32_t ms = usec / 1000;
    
    // Ensure at least a 1ms delay if the requested time is > 0 but < 1000
    if (ms == 0 && usec > 0) {
        ms = 1; 
    }
    
    osDelay(ms); // Yield to FreeRTOS
    return 0;
}

// 2. Implement POSIX gettimeofday using STM32 HAL tick
int _gettimeofday(struct timeval *tv, void *tz)
{
    // (void)tz; // timezone is generally ignored in bare-metal
    
    if (tv != NULL) {
        uint32_t tick = HAL_GetTick(); // Get system uptime in milliseconds
        tv->tv_sec = tick / 1000;              // Convert to seconds
        tv->tv_usec = (tick % 1000) * 1000;    // Remaining milliseconds to microseconds
    }
    return 0;
}

